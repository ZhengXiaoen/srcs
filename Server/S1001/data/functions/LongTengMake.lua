function LongTengChangeMkae(sysarg,index,i)
    index = tonumber(index)
    i = tonumber(i)
    local cfg = LongTengChangeCfg[index]
    if cfg == nil then return end
    cfg = cfg.list[i]
    if Actor.getItemCount(sysarg,cfg.itemid) < 1 then
        Actor.sendTipmsg(sysarg,"材料不足,无法兑换!",ttFlyTip)
        return
    end
	
	if Actor.changeMoney( sysarg, 3, -cfg.YBcount, LogIds.longtengMake, "龙腾男女互换")==false then
		Actor.sendTipmsg(sysarg,"元宝不足",ttFlyTip)
		return 
	end
	
    if Actor.removeItem(sysarg,cfg.itemid,1,-1,-1,-1,"龙腾男女互换",LogIds.longtengMake)~=1 then
		Actor.sendTipmsg(sysarg,"扣除物品失败",ttFlyTip)
		return 
	end
	
    Actor.addItem(sysarg,cfg.destid,0,0,1,cfg.bind,0,"龙腾男女互换",LogIds.longtengMake)
    Actor.sendTipmsg(sysarg,"互换成功!",ttFlyTip)
	 
end
