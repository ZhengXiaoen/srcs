-- 改为成为VIP后直接加到3级，不用手动点击了
VipFunc.learningToNow = function(sysarg)

	local vipLevel = Actor.getIntProperty(sysarg,PROP_ACTOR_VIP_GRADE)
	if vipLevel <= 0 then return end
	
	local config = assert(VipConfig.VipGrade[vipLevel],"VipConfig find error ")
	if config.skillLevelUp == -1 then return end

	local skillId = {
		{1,2,3,4,5,6,63,64},
		{8,9,10,12,14,15,16,65,66},
		{17,20,19,22,21,24,67,69,71}}
		
	local nJob = Actor.getIntProperty(sysarg,PROP_ACTOR_VOCATION)
	local nJobSkill = assert(skillId[nJob],"skill table is nil")
	for _,skill_Id in ipairs(nJobSkill) do
		-- 如果没有学习返回0
		local skillLevel = Actor.getSkillLevel(sysarg,skill_Id)
		-- 如果没有该技能则要帮他加
		if skillLevel < config.skillLevelUp then
			Actor.startLearnSkill(sysarg,skill_Id,config.skillLevelUp)
		end
	end
end


EventCallDispatcher.HandleGetVipReward = function (sysarg, args)
	local level = args[1]
	local vipLevel = Actor.getIntProperty(sysarg,PROP_ACTOR_VIP_GRADE)
	if level < 1 or level > 32 or level > vipLevel then
		Actor.sendTipmsg(sysarg, string.format(Lang.ScriptTips.zf359, level), ttFlyTip)
		return
	end
	
	local vipFlags = Actor.getVipFlags(sysarg)
	local f = System.getIntBit(vipFlags, level - 1)
	if f ~= 0 then
		Actor.sendTipmsg(sysarg,Lang.ScriptTips.zf176,ttFlyTip) --已经领过了
		return
	end
	
	local levelCfg = VipConfig.VipGrade[level]
	if levelCfg == nil or levelCfg.reward == nil then return end
	
	if Awards.Give(sysarg, levelCfg.reward, 990, "领取VIP奖励") ~= true then
		return
	end
	
	vipFlags = System.setIntBit(vipFlags, level - 1, true)
	Actor.setVipFlags(sysarg, vipFlags)
	
	--返回给客户端
	local sGetVipFlags = 8
	local netPack = DataPack.allocPacket(sysarg, 54, sGetVipFlags) -- enVipSystem == 54
	DataPack.writeUInt(netPack, vipFlags)
	DataPack.flush(netPack)
end

EventCallDispatcher.HandleEnterVipScene = function (sysarg, args)
	-- 0 为挂机场景，1 为打宝场景
	local sceneType = args[1]
	
	local vipLevel = Actor.getIntProperty(sysarg,PROP_ACTOR_VIP_GRADE)
	if vipLevel <= 0 then
		Actor.sendTipmsg(sysarg,Lang.ScriptTips.zf661,ttFlyTip)
		return
	end
	
	local levelCfg = VipConfig.VipGrade[vipLevel]
	if levelCfg == nil then return end
	
	if Vip_TelportCondition(sysarg) == false then
		return 
	end	
	
	local sceneCfg = (sceneType == 0) and levelCfg.hookScene or levelCfg.boxScene
		
	if Actor.getSceneId(sysarg) == sceneCfg[1] then return end
		
	Actor.enterScene(sysarg, sceneCfg[1], sceneCfg[2], sceneCfg[3])
end

-- 领取vip buffer
EventCallDispatcher.HandleGetVipBuffer = function (sysarg, args)
	local myVipLv = Actor.getIntProperty(sysarg,PROP_ACTOR_VIP_GRADE);
	if not myVipLv or myVipLv == 0 then
		Actor.sendTipmsg(sysarg,Lang.ScriptTips.v00002, ttFlyTip);
		return;
	end
	
	local var = Actor.getStaticVar(sysarg);
	local vipExpBuffFlags = var.days.vipexpbuff;
	if not vipExpBuffFlags then
		vipExpBuffFlags = 0;
	end
	
	if vipExpBuffFlags > 0 then
		Actor.sendTipmsg(sysarg,Lang.ScriptTips.v00003, ttFlyTip);
		return;
	end
	
	local expbuff = VipPrivilegesCfg[myVipLv].expbuff;
	local nInterval = expbuff.time*60;
	Actor.addBuff(sysarg, 64, 100, expbuff.multiple, expbuff.times, nInterval, expbuff.desc, expbuff.timeOverlay, nil, 0, 0, 0, expbuff.icon);
	Actor.sendTipmsg(sysarg, string.format(Lang.ScriptTips.v00001, myVipLv, expbuff.desc), ttFlyTip);
	var.days.vipexpbuff = 1;
end

