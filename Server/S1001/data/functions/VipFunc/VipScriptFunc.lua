function Vip_TelportCondition(sysarg,config)
	
	--护送皇杆
	local var = Actor.getStaticVar(sysarg)
	if var.ybstate == 1 then
		Actor.sendTipmsg(sysarg,Lang.Activity.k00046, ttFlyTip) 
		return false
	end
	
	--摆摊
	if Actor.hasState(sysarg,esStateStall) then
		Actor.sendTipmsg(sysarg,Lang.stall001.zf137,ttFlyTip)
		return false
	end
	
	--在副本
	if Actor.getFubenId(sysarg) > 0 then
		Actor.sendTipmsg(sysarg,Lang.ScriptTips.zf138,ttFlyTip)
		return false 
	end

	--在武林争霸中
	if Actor.getSceneId(sysarg) == 58 then
		Actor.sendTipmsg(sysarg,Lang.ScriptTips.zf138,ttFlyTip)
		return false
	end
end

function Vip_CheckBagSurplus(sysarg,config)
	
	local nCount = Item.getBagEmptyGridCount(sysarg)
	local nNeedCount = Item.getAddItemNeedGridCount(sysarg,config.id,config.count)
	if nCount < nNeedCount then
		Actor.sendTipmsg(sysarg, string.format(Lang.ScriptTips.mt00001, nNeedCount), ttFlyTip)
		return false
	end
	return true
end

VipFunc.telportToNow = function(sysarg)
	
	local vipLevel = Actor.getIntProperty(sysarg,PROP_ACTOR_VIP_GRADE)
	if vipLevel <= 0 then return end
		
	local config = VipConfig.VipGrade[vipLevel]
	if not config then return end
		
	if Vip_TelportCondition(sysarg) == false then
		return 
	end
	
	if config.shengJingSceneId == 55 then
		System.broadcastTipmsg(string.format(Lang.ScriptTips.zf177,Actor.getName(sysarg)),128+2)
	elseif config.shengJingSceneId == 56 then
		System.broadcastTipmsg(string.format(Lang.ScriptTips.zf178,Actor.getName(sysarg)),128+2)
