-- 旧版本的剩余次数只在首次进入新规则时转换，防止当天已做过任务的角色再次领取。
function GuildXiangYaoChuMoRemaining(sysarg)
	local var = Actor.getStaticVar(sysarg)
	if var.newdays == nil then
		var.newdays = {}
	end
	local days = var.newdays
	if days.Guild_xycmSingleTask == nil then
		local oldRemaining = days.Guild_xycmTime
		if oldRemaining == nil then
			days.Guild_xycmTime = GuildXiangYaoChuMo_Cfg.DailyCount
		else
			local oldLimit = GuildXiangYaoChuMo_Cfg.LegacyDailyCount
			if IsSpeciaTitleVip(sysarg, 2) then
				oldLimit = GuildXiangYaoChuMo_Cfg.LegacyVipDailyCount
			end
			days.Guild_xycmTime = oldRemaining == oldLimit and 1 or 0
			if days.Guild_xycmTime == 0 and var.Guild_xycmFlag == 2 then
				var.Guild_xycmFlag = 1
				var.Guild_xycmKillC = 0
			end
		end
		days.Guild_xycmSingleTask = 1
	end
	if days.Guild_xycmTime == nil or days.Guild_xycmTime < 0 then
		days.Guild_xycmTime = 0
	elseif days.Guild_xycmTime > GuildXiangYaoChuMo_Cfg.DailyCount then
		days.Guild_xycmTime = GuildXiangYaoChuMo_Cfg.DailyCount
	end
	return days.Guild_xycmTime
end

function GuildXiangYaoChuMoReward(sysarg, cfg)
	local count = GuildXiangYaoChuMo_Cfg.LegacyDailyCount
	if IsSpeciaTitleVip(sysarg, 2) then
		count = GuildXiangYaoChuMo_Cfg.LegacyVipDailyCount
	end
	return cfg.zhanLiZhi * count / GuildXiangYaoChuMo_Cfg.LegacyDailyCount,
		cfg.lingLi * count / GuildXiangYaoChuMo_Cfg.LegacyDailyCount
end
